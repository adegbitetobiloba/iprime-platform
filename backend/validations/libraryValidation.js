const Joi = require("joi");
const { STATUSES, DIFFICULTIES, CONTENT_TYPES } = require("../utils/library");

const id = Joi.string().hex().length(24);
const httpsUrl = Joi.string().trim().uri({ scheme: ["https"] }).max(500);

module.exports = {
  subject: Joi.object({
    name: Joi.string().trim().min(2).max(80).required(),
    description: Joi.string().trim().max(500).allow(""),
    group: Joi.string().valid("subject", "exam-prep"),
    order: Joi.number().integer().min(0).max(10000),
    status: Joi.string().valid("active", "archived"),
  }),
  subjectUpdate: Joi.object({
    name: Joi.string().trim().min(2).max(80),
    description: Joi.string().trim().max(500).allow(""),
    group: Joi.string().valid("subject", "exam-prep"),
    order: Joi.number().integer().min(0).max(10000),
    status: Joi.string().valid("active", "archived"),
  }).min(1),
  course: Joi.object({
    title: Joi.string().trim().min(3).max(150).required(),
    description: Joi.string().trim().max(3000).allow(""),
    coverImageUrl: httpsUrl.allow(""),
    subject: id.required(),
    examTags: Joi.array().items(Joi.string().trim().max(30)).max(10),
    objectives: Joi.array().items(Joi.string().trim().min(1).max(300)).max(20),
    difficulty: Joi.string().valid(...DIFFICULTIES),
    estimatedMinutes: Joi.number().integer().min(0).max(100000),
    featured: Joi.boolean(),
  }),
  courseUpdate: Joi.object({
    title: Joi.string().trim().min(3).max(150),
    description: Joi.string().trim().max(3000).allow(""),
    coverImageUrl: httpsUrl.allow(""),
    subject: id,
    examTags: Joi.array().items(Joi.string().trim().max(30)).max(10),
    objectives: Joi.array().items(Joi.string().trim().min(1).max(300)).max(20),
    difficulty: Joi.string().valid(...DIFFICULTIES),
    estimatedMinutes: Joi.number().integer().min(0).max(100000),
    featured: Joi.boolean(),
  }).min(1),
  status: Joi.object({ status: Joi.string().valid(...STATUSES).required() }),
  module: Joi.object({
    title: Joi.string().trim().min(2).max(150).required(),
    description: Joi.string().trim().max(1000).allow(""),
    topics: Joi.array().items(Joi.object({ _id: id, title: Joi.string().trim().min(1).max(150).required() })).max(50),
  }),
  moduleUpdate: Joi.object({
    title: Joi.string().trim().min(2).max(150),
    description: Joi.string().trim().max(1000).allow(""),
    topics: Joi.array().items(Joi.object({ _id: id, title: Joi.string().trim().min(1).max(150).required() })).max(50),
  }).min(1),
  lesson: Joi.object({
    title: Joi.string().trim().min(2).max(150).required(),
    topicId: id.allow(null),
    contentType: Joi.string().valid(...CONTENT_TYPES).required(),
    body: Joi.string().max(60000).allow(""),
    videoUrl: Joi.string().trim().max(500).allow(""), // parsed server-side; only YouTube/Vimeo accepted
    externalUrl: httpsUrl.allow(""),
    estimatedMinutes: Joi.number().integer().min(0).max(1000),
    practice: Joi.object({ exam: id.allow(null), topic: Joi.string().trim().max(120).allow("") }),
    requiresQuizPass: Joi.boolean(),
  }),
  lessonUpdate: Joi.object({
    title: Joi.string().trim().min(2).max(150),
    topicId: id.allow(null),
    body: Joi.string().max(60000).allow(""),
    videoUrl: Joi.string().trim().max(500).allow(""),
    externalUrl: httpsUrl.allow(""),
    estimatedMinutes: Joi.number().integer().min(0).max(1000),
    practice: Joi.object({ exam: id.allow(null), topic: Joi.string().trim().max(120).allow("") }),
    requiresQuizPass: Joi.boolean(),
    status: Joi.string().valid(...STATUSES),
  }).min(1),
  reorder: Joi.object({ ids: Joi.array().items(id).min(1).max(500).unique().required() }),
  // Events reported by the student's browser. The server clamps and cross-checks all of them.
  progress: Joi.object({
    videoDurationSec: Joi.number().min(0).max(21600),
    videoPositionSec: Joi.number().min(0).max(21600),
    page: Joi.number().integer().min(1).max(5000),
    pageCount: Joi.number().integer().min(1).max(5000),
    activeSecondsDelta: Joi.number().min(0).max(60),
    reachedEnd: Joi.boolean(),
    markedDone: Joi.boolean(),
  }).min(1),
  note: Joi.object({ text: Joi.string().trim().max(5000).allow("").required() }),
  material: Joi.object({
    title: Joi.string().trim().min(3).max(150).required(),
    kind: Joi.string().valid("syllabus", "textbook", "past-questions", "notes", "other").required(),
    description: Joi.string().trim().max(1500).allow(""),
    author: Joi.string().trim().max(120).allow(""),
    subject: id.allow(null, ""),
    examTags: Joi.array().items(Joi.string().trim().max(30)).max(10),
    source: Joi.string().valid("link", "pdf", "text", "image").required(),
    url: httpsUrl.allow(""),
    body: Joi.string().max(200000).allow(""),
    sourceNote: Joi.string().trim().max(300).allow(""),
    featured: Joi.boolean(),
  }),
  materialUpdate: Joi.object({
    title: Joi.string().trim().min(3).max(150),
    kind: Joi.string().valid("syllabus", "textbook", "past-questions", "notes", "other"),
    description: Joi.string().trim().max(1500).allow(""),
    author: Joi.string().trim().max(120).allow(""),
    subject: id.allow(null, ""),
    examTags: Joi.array().items(Joi.string().trim().max(30)).max(10),
    url: httpsUrl.allow(""),
    body: Joi.string().max(200000).allow(""),
    sourceNote: Joi.string().trim().max(300).allow(""),
    featured: Joi.boolean(),
  }).min(1),
  materialProgress: Joi.object({ page: Joi.number().integer().min(1).max(5000), pageCount: Joi.number().integer().min(1).max(5000), percent: Joi.number().min(0).max(100) }).or("page", "percent"),
  shelf: Joi.object({ shelf: Joi.string().valid("want", "reading", "done", "none").required() }),
  countdown: Joi.object({
    label: Joi.string().trim().min(2).max(60).required(),
    date: Joi.string().pattern(/^\d{4}-\d{2}-\d{2}$/).required(),
    official: Joi.boolean().required(),
    enabled: Joi.boolean().required(),
    note: Joi.string().trim().max(200).allow(""),
  }),
};
